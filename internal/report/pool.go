package report

import (
	"fmt"
	"io"
	"sort"
	"strings"
	"text/tabwriter"

	"github.com/mehdashti/limit-ledger/internal/calibrate"
	"github.com/mehdashti/limit-ledger/internal/share"
)

// Pool prints the pooled community table: per plan, the weights that fit all shared
// observations best, and how far each file is from the pool. With markdown, it
// prints a Markdown page instead (for community/TABLE.md).
func Pool(w io.Writer, pools []share.PlanPool, bad map[string]error, markdown bool) error {
	if markdown {
		return poolMarkdown(w, pools, bad)
	}
	if len(pools) == 0 {
		fmt.Fprintln(w, "No valid tables.")
	}
	for _, p := range pools {
		fmt.Fprintf(w, "plan %s: %s, %d account-weeks\n", p.Plan, plural(p.Files, "table"), p.Observations)
		tw := tabwriter.NewWriter(w, 0, 0, 2, ' ', tabwriter.AlignRight)
		fmt.Fprintln(tw, "\tcache write\tcache read\tinput\toutput\t1% of the week\tspread\t")
		line := func(name string, h calibrate.Hypothesis) {
			fmt.Fprintf(tw, "%s\t%.4g\t%.4g\t%.4g\t1\t%s units\t%.1f%%\t\n", name, h.Weights[calibrate.CacheWrite],
				h.Weights[calibrate.CacheRead], h.Weights[calibrate.Input], Tokens(int64(h.PerPercent)), h.Spread*100)
		}
		line("pooled fit", p.Best)
		for _, r := range calibrate.References {
			line(r.Name, p.References[r.Name])
		}
		if err := tw.Flush(); err != nil {
			return err
		}
		fmt.Fprintln(w, "\neach table against the pool (cost of 1% under the pooled weights):")
		for _, f := range sortedFiles(p.PerFile) {
			fmt.Fprintf(w, "  %-40s %+.0f%%\n", f, p.PerFile[f]*100)
		}
		fmt.Fprintln(w)
	}
	for _, f := range sortedErrs(bad) {
		fmt.Fprintf(w, "rejected %s: %v\n", f, bad[f])
	}
	return nil
}

func poolMarkdown(w io.Writer, pools []share.PlanPool, bad map[string]error) error {
	var b strings.Builder
	b.WriteString("# Community weights table\n\n")
	b.WriteString("Generated by `limit-ledger community pool community --markdown`. Do not edit by hand.\n\n")
	b.WriteString("Weights are relative to one Opus 5.5 output token. \"1% of the week\" is how many such units one\n")
	b.WriteString("percent of the weekly limit was worth. Spread is how much that varies across the shared weeks\n")
	b.WriteString("under those weights. These are estimates from volunteers' own usage, not official figures.\n\n")
	if len(pools) == 0 {
		b.WriteString("No tables yet.\n")
	}
	for _, p := range pools {
		fmt.Fprintf(&b, "## %s\n\n%s, %d account-weeks.\n\n", p.Plan, plural(p.Files, "table"), p.Observations)
		b.WriteString("| | cache write | cache read | input | output | 1% of the week | spread |\n|---|---|---|---|---|---|---|\n")
		row := func(name string, h calibrate.Hypothesis) {
			fmt.Fprintf(&b, "| %s | %.4g | %.4g | %.4g | 1 | %s | %.1f%% |\n", name, h.Weights[calibrate.CacheWrite],
				h.Weights[calibrate.CacheRead], h.Weights[calibrate.Input], Tokens(int64(h.PerPercent)), h.Spread*100)
		}
		row("**pooled fit**", p.Best)
		for _, r := range calibrate.References {
			row(r.Name, p.References[r.Name])
		}
		b.WriteString("\n| table | cost of 1% vs pool |\n|---|---|\n")
		for _, f := range sortedFiles(p.PerFile) {
			fmt.Fprintf(&b, "| %s | %+.0f%% |\n", f, p.PerFile[f]*100)
		}
		b.WriteString("\n")
	}
	if len(bad) > 0 {
		b.WriteString("## Rejected files\n\n")
		for _, f := range sortedErrs(bad) {
			fmt.Fprintf(&b, "- %s: %v\n", f, bad[f])
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func sortedFiles(m map[string]float64) []string {
	var l []string
	for k := range m {
		l = append(l, k)
	}
	sort.Strings(l)
	return l
}

func sortedErrs(m map[string]error) []string {
	var l []string
	for k := range m {
		l = append(l, k)
	}
	sort.Strings(l)
	return l
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}
